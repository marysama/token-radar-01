// Token Radar's model, radar-2: one snapshot of the protocol universe in, one ranked board out.
//
// The board covers EVERY rankable pre-token protocol in the snapshot (198 rows: the 40 watchlist
// protocols, the 12 other rankable protocols at or above the floor, and all 146 rankable ones below
// it). The watchlist is the floor, never the ceiling: the early radar is the whole field below it.
//
// A protocol is rankable only when it records no token AND it is not a wrapped, staked or bridged
// product of a token that already trades: the field guide's own rule (category Bridge, Canonical
// Bridge, Liquid Staking, Liquid Restaking, Restaked BTC or CEX; a name carrying a whole word
// wrapped, staked or staking; a name beginning with an exchange's name; a versioned pool). WBTC is
// Bitcoin on Ethereum and Binance staked ETH is ETH in a staking product: neither is a protocol
// still waiting on a launch of its own, so they are set aside with the live tokens, not ranked.
// 91 such products are set aside; the board ranks only genuine future launches.
//
// Implied value follows only from the snapshot's own figures:
//
//   base       = tvl_usd x BASE_MULTIPLE
//   growth     = clamp(change_7d, -60, 120) per cent
//   growthMult = 1 + (growth / 100) x GROWTH_WEIGHT
//   maturity   = 0.6 + min(age_days, 1095) / 1095 x 0.4   (age_days unknown: 365)
//   chainMult  = 1 + 0.04 x min(chains - 1, 5)            (reach: more chains, more users)
//   earlyMult  = 1.10 when age_days < 365 and growth > 20 (young and fast-growing: the early signal),
//                else 1.00
//   implied    = max(1, round(base x growthMult x maturity x chainMult x earlyMult))
//
// The constants are stated in the dashboard and changeable in the model sandbox. No protocol name is
// ever special-cased: the same function scores every row.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

